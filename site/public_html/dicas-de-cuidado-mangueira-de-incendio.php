						<h2>Como Realizar as Inspeções</h2>

						<p>Antes da utilização da mangueira de combate a incêndio, deve-se garantir que a inspeção seja feita rigorosamente seguindo os passos abaixo: </p>
						<ol>
							<li>Inspeção geral a cada três meses; </li>
							<li>Ensaio hidrostático a cada 12 meses, e se recomenda uma frequência maior para mangueiras de combate a incêndio que estejam expostas a condições extremas de temperatura, umidade, piso abrasivo ou com produtos químicos e derivados de petróleo.</li>
							<li>Manter registros históricos da vida útil da mangueira por meios de planilhas e fichas, com controle de datas de inspeção, manutenção e utilização. </li>
						</ol>
						<h2>Preservação</h2>
						<p>Quando armazenada a mangueira de combate a incêndio, deve-se prestar atenção em alguns tópicos para a adequada preservação e cuidados com a mangueira. São estes:</p>
						<ul>
							<li> Cantos e objetos pontiagudos ao redor;</li>
							<li> Manobras agressivas com a mangueira</li>
							<li>Fechamento súbito do registro;</li>
							<li>Exposição direta ao fogo ou superfícies quentes;</li>
							<li> Quedas e arraste;</li>
							<li>Evitar guardar a mangueira molhada;</li>
							<li>Evitar manter a mangueira conectada ao hidrante após a utilização.</li>
							<li> Evitar  arrastar a mangueira de combate a incêndio.</li>
						</ul>

						<h2>Possibilidade de Falha</h2>
						<ul>
							<li> Desgaste na parte têxtil e região do vinco; </li>
							<li>Desgaste por abrasão externa;</li>
							<li>Manchas/resíduos em sua exterioridade; </li>
							<li>Desprendimento de qualquer parte do revestimento; </li>
							<li> Deslize nas partes de montagem; </li>
							<li>Impedimento de acoplagem nas partes de montagem;</li>
							<li>Deformações por quedas, golpes ou arraste; </li>
							<li> Falta de vedação emborrachada;</li>
							<li>Ressecamento; </li>
							<li> Cortes. </li>
						</ul>

						<h2>Limpeza</h2>

						<p>A limpeza da mangueira de combate a incêndio deve ser realizada sempre que ela apresentar resíduos, mofos ou manchas na parte externa ou interna (visível). É possível realizar uma limpeza a seco, que parte da utilização de uma escova de cerdas não metálicas (longas e macias, que não arranhem a superfície têxtil), e o escovamento deve ser direcionado em forma cruzada, para que permaneça no sentido da trama e do urdume. </p>
						<p>Caso seja necessário operar uma lavagem, é ideal que se utilize água potável e, no máximo, sabão neutro, sem o uso de nenhum produto químico ou abrasivos, que podem danificar e inutilizar a mangueira. </p>
						<p>A secagem deve ser realizada tanto internamente quanto externamente após o uso ou limpeza, mantendo a mangueira na sombra (nunca no sol), em posição vertical.</p>
						<h2>Armazenagem</h2>
						<p>A mangueira de combate a incêndio que tenha passado em todos os testes de qualidade, definições e manutenção, estando pronta para o uso, deve ser armazenada em local seco, ventilado e segura da ação direta de raios solares ou ambientes com atmosferas agressivas.</p>
						<p>Com essas dicas, manter sua mangueira  em condições plenas para a utilização fica muito mais fácil, garantindo sua segurança e uso ideal! </p>
