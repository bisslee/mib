						<h2>Definições</h2>

						<p>As definições servem para garantir que a mangueira de combate a incêndio esteja em condições perfeitas para utilização de acordo com a norma. Pontos importantes:</p>

						<ul>
							<li>É importante que se faça a inspeção frequentemente nas mangueiras de combate a incêndio, verificando visualmente se a mesma se encontra em boa condições;</li>
							<li>Além disso, após sua utilização da mangueira de combate a incêndio, um serviço de manutenção se faz necessário, mantendo-a preparada para futuras aplicações;</li>
							<li>Verificação do vinco, que é a dobra existente ao longo do comprimento da mangueira, especialmente criada para seu enrolamento em forma plana, gerando melhores acomodações;</li>
							<li>Verificação do esguicho que deve ser regulável, de acordo com a vazão e diâmetro da mangueira de combate a incêndio, forma, direção e alcance do jato desejado e necessário para a operação;</li>
							<li>Aferir a qualidade da trama da mangueira de combate a incêndio – conjunto de fios que dão reforço têxtil transversal à mangueira;</li>
							<li> Aferir a qualidade do urdume – conjunto de fios para reforço têxtil em sentido longitudinal;</li>
							<li> Também é importantíssimo garantir que todas as peças utilizadas na mangueira de combate a incêndio são originais e se encontram em bom estado, com garantias em ordem. </li>
