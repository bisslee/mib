                    <p>A presença da <strong>luminária de emergência industrial</strong> visa propiciar um ambiente mais
                    seguro e preparado caso ocorram falhas, panes e incidentes que demandem a
                    evacuação rápida de pessoas e o esvaziamento da estrutura predial.</p>
                
                
                    <p>Além disso, as luminárias também são essenciais em casos de falta ou interrupção no
                    fornecimento de energia elétrica, uma vez que são dotadas de uma bateria que lhes
                    permite funcionar mesmo quando não há luzes no recinto industrial.</p>
                    
                    <p>Esses dispositivos não são apenas necessários, mas também, exigidos legalmente.
                    Logo, o não cumprimento das normas de segurança pode acarretar em multas,
                    inviabilização das estruturas prediais, perdas materiais e, o mais importante, perdas
                    humanas.</p>
                    
                    <br>
                    <h2><strong>Especificidades sobre a luminária de emergência industrial</strong></h2>
                    
                    <p>As luminárias de emergência são equipamentos robustos e devem estar sempre
                    prontas para serem usadas, afinal, nunca se sabe quando pode ocorrer um incidente
                    ou falta de energia elétrica. Algumas informações importantes sobre esse tipo de
                    produto são:</p>
                    
                    <ul>
                        
                    <li>Dotadas de uma bateria interna recarregável, as luminárias de emergência
                    aplicadas nas indústrias possuem longa durabilidade e podem ser utilizadas
                    por até dez anos sem apresentar falhas ou queimar;</li>
                    <li>Por serem dotados de lâmpadas de LED, esses equipamentos consomem
                    pouca energia proveniente da bateria e não agridem o meio ambiente, sendo,
                    por isso, ecologicamente corretos, fabricados com materiais recicláveis e
                    altamente funcionais;</li>
                    <li>As luminárias devem ficar constantemente ligadas na tomada, pois a energia
                    elétrica é utilizada para manter as baterias carregadas, a fim de que o sistema
                    inteligente acione as luzes automaticamente caso a eletricidade seja
                    interrompida;</li>
                    <li>A quantidade de lâmpadas LED pode variar de acordo com o modelo adquirido,
                    bem como a sua potência. Por isso é importante avaliar a extensão do local no
                    qual as luminárias serão instaladas e, assim, optar pelo equipamento mais
                    adequado;</li>
                    <li>É recomendada a realização de testes a cada três meses para certificar se as
                        luminárias estão funcionando corretamente, para tanto, basta interromper o
                        fornecimento de energia elétrica e verificar se os equipamentos são acionados
                        corretamente.</li>

                    
                    </ul>
                    
