 <li>tipo 3: possui uma dupla capa, fazendo com que ela esteja preparada para

combater incêndios em áreas navais;</li>

 <li>tipo 4: com revestimento externo e interno, a mangueira é ideal para refinarias

de petróleo e petroquímicas, local em que é necessário uma alta resistência </li>

 <li>tipo 5: possui as mesmas aplicações da anterior, porém, é revestida por 2

camadas de borracha sintética, o que aumenta a sua resistência.</li>

</ul>

