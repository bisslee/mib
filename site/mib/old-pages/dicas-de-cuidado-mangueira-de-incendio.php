 <h2>Como Realizar as Inspeções</h2>

 <p>Antes da utilização da mangueira de combate a incêndio, deve-se garantir que a inspeção seja feita rigorosamente seguindo os passos abaixo: </p>

 <ol>

 <li>Inspeção geral a cada três meses; </li>

 <li>Ensaio hidrostático a cada 12 meses, e se recomenda uma frequência maior para mangueiras de combate a incêndio que estejam expostas a condições extremas de temperatura, umidade, piso abrasivo ou com produtos químicos e derivados de petróleo.</li>

 <li>Manter registros históricos da vida útil da mangueira por meios de planilhas e fichas, com controle de datas de inspeção, manutenção e utilização. </li>

