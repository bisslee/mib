 para ser utilizada em edifícios residenciais para apagar chamas em materiais sólidos,

 como madeira, papel e tecido. Já o tipo 2 das mangueiras de incêndio são indicadas

 para o uso em edifícios comerciais e pelo Corpo de Bombeiros.</p>

 <p>Também são encontradas as mangueiras do tipo 3, que são indicadas para a área naval e

 pelo Corpo de Bombeiros, por serem resistentes à abrasão e por ser ideal para apagar

 chamas em situações mais críticas. Os tipos 4 e 5 das mangueiras de incêndio possuem

 maior pressão e altíssima resistência à abrasão e seu uso é específico para o Corpo de

 Bombeiros e para indústrias que trabalham com combustíveis e com metais que

 inflamam espontaneamente, como por exemplo, magnésio, potássio e o sódio.</p>

 <p>É de suma importância verificar as especificações nas extremidades da <strong>mangueira de

 incêndio</strong> ao realizar a compra, como o selo impresso de qualidade da ABNT, nome do

 fabricante, tipo da, data de fabricação e o número da norma para que você possa

 verificar a autenticidade do produto e garantir que o mesmo não sofreu adulteração e

