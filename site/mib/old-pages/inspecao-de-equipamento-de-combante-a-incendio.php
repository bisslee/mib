                <br>

                

                <p>A realização da <strong>inspeção de equipamentos de combate a incêndio</strong> é uma

                ação altamente necessária a fim de garantir que extintores, mangueiras e

                hidrantes apresentem perfeito funcionamento quando solicitados.</p>

                

                

                <p>Por isso, a inspeção desses tipos de equipamentos deve ser realizada apenas

                por profissionais capacitados para este fim, uma vez que, após o término das

                verificações, são emitidos laudos que devem ser guardados para serem

                apresentados durante a fiscalização de agentes governamentais, como o

                Corpo de Bombeiros.</p>

                

                <h2><strong>Saiba como é feita a inspeção de equipamentos de combate a

                        incêndio</strong></h2>

                <br>

                

                <p>A inspeção profissional difere da amadora, pois nela são realizados testes e

                verificações em todos os componentes dos equipamentos de combate a

                incêndio a fim de certificar seu total funcionamento, estado de conservação e

                apontar a necessidade de manutenções.</p>

                

                <p>É válido ressaltar também que inspeções visuais são indispensáveis e podem

                ser feitas mesmo por pessoas não treinadas; porém, em hipótese alguma, elas

                substituem aquelas realizadas por profissionais, que são mais completas e

                efetivamente confiáveis.</p>

                

                <p>Conheça os equipamentos de combate a incêndios mais comuns e suas

                        inspeções:</p>

                

                <ul>

                    

                    <li><strong>Inspeção de mangueiras:</strong> A inspeção das mangueiras pode incluir a

                    realização de testes hidrostáticos e deve ser feita ao menos uma vez ao

                    ano. Os profissionais verificam todos os componentes, tais como

                    engates e acoplamentos, bem como a presença da chave storz.

                    Mangueiras com defeitos podem apresentar queda em seu rendimento,

                    tais como: perda de pressão do jato de água e até vazamentos. Além

                    disso, devem ser enroladas corretamente para estarem sempre prontas

                    para o uso;</li>

                    

                    <li><strong>Inspeção de extintores:</strong> A verificação dos extintores inclui a checagem

                    de componentes como válvulas e lacres, além de seu correto



                    posicionamento nos ambientes, que não podem apresentar elementos

                    que dificultem seu acesso e utilização em situações de emergência.

                    Além disso, é preciso se certificar de que o extintor adequado está

                    disponível para uso, afinal cada tipo é indicado para combater o fogo em

                    materiais e locais específicos, tais como componentes químicos,

                    presença de eletricidade e materiais combustíveis;</li>

                    

                    <li><strong>Inspeção de bombas e hidrantes:</strong> Dotados de conectores que

                    permitem o acoplamento das mangueiras de incêndio, as bombas e

                    hidrantes devem ser inspecionados anualmente, uma vez que pancadas,

                    por exemplo, podem deformar os engates, fator que acarreta em

                    problemas na vedação.</li>

                

                </ul>

                

