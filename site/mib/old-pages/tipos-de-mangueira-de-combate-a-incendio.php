 <h2><strong>Especificações técnicas para mangueiras de combate a

 incêndio</strong></h2>

 <p>As especificações são regidas pela ABNT – Associação Brasileira de Normas

 Técnicas - e determinam o tipo ideal de mangueira a ser usada em virtude do

 contexto e condições de aplicação. Desse modo, sua observância é de suma

 importância.</p>

 <p>Além disso, é recomendado dar preferência às mangueiras que foram

 previamente submetidas a testes de segurança, tais como os realizados pelo

 Inmetro - Instituto Nacional de Metrologia, Qualidade e Tecnologia –, o que

 garante total segurança durante sua aplicação.</p>

 <p>As mangueiras são divididas em 5 categorias, delimitadas pela pressão

 máxima de trabalho suportada por cada equipamento, local no qual devem ser

 aplicadas e condições de abrasividade que podem afetar sua durabilidade.</p>

 <ul>

 <li>Assim sendo, as mangueiras do tipo 1 são ideais para aplicação em

 edifícios residenciais e possuem pressão máxima de trabalho de 980

 KPa (10kgf/cm²). Entretanto, não devem ser aplicadas em contextos

 com alta abrasão, tais como indústrias.</li>

 <li>Em edifícios comerciais, industriais ou para aplicação pelo Corpo de

 Bombeiros, o tipo 2 é o mais indicado, devido à pressão máxima de

 trabalho de 1370 KPa (14kgf/cm²). O tipo 4 apresenta os mesmos

 índices de pressão, mas é aplicado apenas na indústria.

 <li>As mangueiras do tipo 3 são destinadas às áreas industriais e navais por

 apresentarem alta resistência à abrasão, além de possuírem pressão

 máxima de trabalho de 1470 KPa (15kgf/cm²). É a mais alta entre todos

 os modelos listados pela ABNT.</li>

 <li>Por fim, as mangueiras do tipo 5 são destinadas à área industrial, e

 apesar de apresentar a mesma pressão máxima de trabalho dos tipos 2

 e 4 - 1370 KPa (14kgf/cm²), são mais resistentes à abrasão e às

 superfícies quentes.</li>

 </ul>

