 <h2><strong>2 MANUAL TÉCNICO</strong></h2>

 <h3>2.1 APLICAÇÃO</h3>

 <p>Certificar que o tipo de mangueira de incêndio fabricada conforme NBR 11861 é adequado ao local

 e as condições de aplicação, conforme norma ABNT-NBR 11861:</p>

 <ul>

 <li>Mangueira Tipo 1 ABNT NBR 11861 – Destina-se a edifícios de ocupação residencial. Pressão

 de trabalho máxima de 980 kPa (10 kgf/cm2).</li>

 <li>Mangueira Tipo 2 ABNT NBR 11861 – Destina-se a edifícios comerciais e industriais ou Corpo

 de Bombeiros. Pressão de trabalho máxima de 1.370 kPa (14 kgf/cm2).</li>

 <li>Mangueira Tipo 3 ABNT NBR 11861 – Destina-se a área naval e industrial ou Corpo de

 Bombeiros onde é indispensável maior resistência à abrasão. Pressão de trabalho máxima de

 1.470 kPa (15 kgf/cm2).</li>

 <li>Mangueira Tipo 4 ABNT NBR 11861 – Destina-se a área industrial, onde é desejável maior

 resistência à abrasão e e resistência a produtos químicos. Pressão de trabalho máxima de

 1.370 kPa (14 kgf/cm2).</li>

 <li>Mangueira Tipo 5 ABNT NBR 11861 – Destina-se a área industrial, onde é desejável uma alta

 resistência à abrasão. Pressão de trabalho máxima de 1.370 kPa (14 kgf/cm2)</li>

 </ul>

 <h3><strong>2.2 PRÉ-USO</strong></h3>

 <ul>

 <li>Verificar se a pressão na linha é compatível com a pressão de trabalho de mangueira.</li>

 <li>Adotar instruções contidas na Norma ABNT-NBR 12779:2009 – INSPEÇÃO, MANUTENÇÃO E

CUIDADOS EM MANGUEIRAS DE INCÊNDIO.</li>

 <li>A mangueira de incêndio deve ser utilizada por pessoal treinado.</li>

 <li>Não armazenar sob a ação direta dos raios solares e/ou vapores de produtos químicos

agressivos.</li>

<li>Não utilizar a mangueira para nenhum outro fim (lavagem de garagens, pátios etc.) que não seja

o combate a incêndio.</li>

<li>Para a sua maior segurança, não utilize as mangueiras das caixas/abrigos em treinamentos de

brigadas, evitando danos e desgastes. As mangueiras utilizadas em treinamento de brigadas

devem ser mantidas somente para este fim.</li>

<li>Evitar a queda das uniões.</li>

<li>Nunca guardar a mangueira molhada após a lavagem, uso ou ensaio hidrostático.</li>

<li>Não arrastar a mangueira sem pressão , isto pode causar furos no vinco</li>

 </ul>

 <h3><strong>2.2 EM USO:</strong></h3>

 <ul>

 <li>Evitar a passagem da mangueira sobre cantos vivos, objetos cortantes ou pontiagudos, que

possam danificá-la.</li>

<li>Não curvar acentuadamente a extremidade conectada com o hidrante, pode causar o desempatamento da mangueira (união).</li>

<li>Cuidado com golpes de aríete na linha causados por entrada de bomba ou fechamento abrupto

de válvulas e esguichos (segundo a norma americana NFPA 1962, a pressão pode atingir sete

vezes, ou mais, a pressão estática de trabalho). Isso pode romper ou desempatar uma

mangueira.</li>

<li>Quando não for possível evitar a passagem de veículos sobre a mangueira, deve ser utilizado

um dispositivo de passagem de nível.</li>

 </ul>

 <h3><strong>2.3 INSPEÇÃO E MANUTENÇÃO :</strong></h3>

 <ul>

 <li>Toda mangueira, quando em uso (em prontidão para combate a incêndio), deve ser

 inspecionada a cada 6 (seis) meses e manutenida a cada 12 (doze) meses, conforme a norma

 NBR 12779:2009. Estes serviços devem ser realizados por empresa especializada.</li>

 </ul>

 <h3><strong>NOTAS:</strong></h3>

 <ul>

 <li>O recomendamos que o usuário identifique individualmente as mangueiras sob sua

 responsabilidade, mantendo registros históricos de sua útil e a guarda dos relatórios de inspeção

 e manutenção.</li>

 <li>Após o ensaio hidrostático, a mangueira deve retornar, preferencialmente, para o mesmo

 hidrante ou abrigo em que se encontrava antes do ensaio. Consultar a Norma NBR 12779:2009

 para formas de acondicionamento.</li>

 </ul>

