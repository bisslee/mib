                  <h3><strong>QUANDO OPTAR PELO EXTINTOR DE INCÊNDIO TIPO K 6 LITROS?</strong></h3>



                  <p>O extintor de incêndio tipo K 6 litros é indicado para apagar chamas provenientes ou que

estão em curso em ambientes que contêm quantidades de gordura vegetal ou animal, não por

acaso, ele está sempre presente em cozinhas industriais, restaurantes, cantinas e lanchonetes.</p>



<p>Isso acontece porque os extintores foram desenvolvidos para não apenas conter os incêndios,

mas fazê-lo de forma segura: tentar apagar chamas em óleo de cozinha ou banha com água,

por exemplo, agrava o incêndio, já que o H2O pode alimentar ainda mais o fogo.</p>



<p><strong>COMPOSIÇÃO DO EXTINTOR DE INCÊNDIO TIPO K 6 LITROS</strong></p>



<p>O extintor de incêndio tipo K 6 litros possui uma composição específica para combater as

chamas de classe K: a solução de acetato de potássio, que não propaga o incêndio e o faz

cessar de maneira rápida, abafando as chamas e extinguindo sua combustão.</p>



<p>Assim, a existência deste e de outros tipos de extintores implica no entendimento que para

apagar incêndios é preciso conhecer as diferentes classes de fogo e, ainda, identificar os

componentes existentes em cada ambiente e que podem agravar ou causar incêndios.</p>



<p>A carga dos extintores também deve ser observada, pois é importante que ela dê conta de

extinguir incêndios pontuais, para que eles não tomem grandes proporções. O extintor de

incêndio tipo K 6 litros tem excelente capacidade, mesmo em cozinhas mais amplas.</p>



<p><strong>INSPEÇÃO DO EXTINTOR DE INCÊNDIO TIPO K 6 LITROS</strong></p>



<p>Não basta ter o extintor de incêndio tipo K 6 litros, é preciso cuidar para que ele esteja

sempre em boas condições e pronto para uso, afinal, o surgimento de chamas muitas vezes

não pode ser evitado, mas sua propagação e o risco que elas podem trazer às pessoas, sim.</p>



<p>Para tanto, é preciso tomar alguns cuidados quando na manutenção do extintor classe K:</p>



<ul>

            <li>Cada extintor deve ter uma folha de inspeção;</li>

            <li>Todos os meses o extintor deve ser examinado a fim de constatar se as válvulas, lacre,

bico, manômetros e aspecto externo estão em boas condições e funcionando;</li>

            <li>Cada extintor deve ter uma etiqueta que fique bem protegida para que os dados nela

contidos não sofram danos. Já os dados preenchidos devem ser a data última e

próxima recarga e número de identificação;</li>

            <li>Caso o extintor de incêndio tipo K 6 litros sofra perda de, no máximo, 10% de seu

peso, é preciso providenciar sua recarga;</li>

            <li>As recargas só podem ser feitas por profissionais, com equipamentos adequados,

componentes descritos no rótulo do extintor e em concordância com as normas

técnicas em vigência no Brasil.</li>

</ul>



