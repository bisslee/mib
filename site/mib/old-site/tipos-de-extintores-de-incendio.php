                  <p>O QUE É PRECISO SABER SOBRE OS TIPOS DE EXTINTORES DE INCÊNDIO E SUAS
PARTICULARIDADES</p>

<p>Os extintores de incêndio são um dos equipamentos mais fundamentais quando
pensamos no quesito segurança de qualquer ambiente, já que são produzidos com a
finalidade de controlar os princípios de um incêndio em situações de emergência.</p>

<p>Porém, é preciso entender que para cada situação de emergência, existem tipos de
extintores de incêndio específicos – por isso, as informações sobre substâncias
armazenadas e os usos em cada caso, devem estar no rótulo de cada extintor, assim
como as informações de manuseio e medidas para evitar acidentes ainda piores.</p>

<p>OS PRINCIPAIS TIPOS DE EXTINTORES DE INCÊNDIO</p>

<p>Uma das grandes tendências do mercado é, justamente, um extintor que seja capaz de
combater o fogo em materiais como: a madeira, o papel, o tecido, os materiais sólidos
em geral, os líquidos inflamáveis e os equipamentos elétricos.</p>

<p>No entanto, o próprio mercado já oferece uma série de tipos de extintores de
incêndio para atender às necessidades em cada caso. Entenda quais são os quatro
principais tipos de extintores de incêndio e quais os materiais que ele consegue
combater:</p>

<p>- Extintor com água pressurizada: são indicados para os incêndios de classe A, ou seja,
aqueles que envolvem materiais, como madeira, papel, tecidos e materiais sólidos em
geral. Nesse caso, a água age por meio do resfriamento ou o abafamento, tudo
depende da forma como é utilizado.</p>

<p>- Extintor com gás carbônico (CO2): são direcionados para o combate de incêndios de
classe C – acidentes que envolvem, principalmente, equipamentos elétricos
energizados – já que este modelo não é um condutor de eletricidade. Ainda assim,
esse tipo pode ser utilizado em incêndios de classe A e B.</p>

<p>- Extintor com pó químico seco: são os mais indicados para incêndios de classe B, ou
seja, aqueles resultados de líquidos inflamáveis, agindo assim, por abafamento.</p>

<p>- Extintor com pó químico especial: também agindo por abafamento, esse modelo é
próprio para combater incêndios de classe D, ou seja, acidentes que envolvem metais
inflamáveis.</p>

<p>É importante lembrar que, além dos tipos de extintores de incêndio descritos acima,
também existe a classe K, que se configura para combater incêndios que envolvem
óleos e gorduras.</p>

<p>ESCOLHER OS TIPOS DE EXTINTORES DE INCÊNDIO ADEQUADOS É IMPRESCINDÍVEL</p>

