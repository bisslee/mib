                <p>Algumas informações sobre extintores de incêndio devem ser de conhecimento geral, afinal,
eles foram criados para salvar a vida de pessoas, conservar estruturas prediais e evitar que o
surgimento de um foco de chamas possa se propagar e causar grandes estragos.</p>

<p>Por isso, os profissionais da BS Brasil Segurança, referência no segmento comercial de
equipamentos de prevenção e combate a incêndios, trazem as informações sobre extintores
de incêndio que é preciso saber!</p>

<p><strong>AS MAIS IMPORTANTES INFORMAÇÕES SOBRE EXTINTORES DE INCÊNDIO</strong></p>

<p>O extintor de incêndio pode ser descrito como um cilindro que contém determinada
substância sob pressão em seu interior. Para seu correto acionamento, ele conta com bico,
lacre de segurança e válvulas. O manômetro indica os níveis interiores de pressão.</p>

<p>A presença dos extintores de incêndio é obrigatória em prédios, condomínios horizontais,
indústrias e estabelecimentos comerciais, pois em virtude da grande circulação de pessoas e
da presença de materiais inflamáveis é preciso tomar as precauções necessárias.</p>

<p>Os extintores devem ser inspecionados uma vez ao mês para que suas condições sejam
avaliadas. Logo, é preciso verificar elementos como o bico, as válvulas, a carga, prazo de

validade, data da última e da próxima recarga, além de registrar todas as informações sobre
extintores de incêndio.</p>

<p><strong>INFORMAÇÕES SOBRE EXTINTORES DE INCÊNDIO: CLASSES</strong></p>

<p>Para cada classe de fogo, uma classe de extintor, como orienta a equipe da BS Brasil
Segurança, que conta com amplo catálogo de extintores para atender às demandas de
solicitantes e empresas de todos os portes.</p>

<p>Assim, saber que existem diferentes classes é uma das mais valiosas informações sobre
extintores de incêndio, pois permite escolher aquele que efetivamente pode combater as
chamas. Estas, por sua vez, podem ser provenientes de diferentes materiais:</p>

<ul>
            <li>Classe A: Combate o fogo em materiais fibrosos e sólidos, como madeira, papel e
tecido. A substância extintora da carga do extintor classe A é água;</li>
            <li>Classe B: Combate o fogo em líquidos e gases inflamáveis, como gasolina e vaselina. A
substância extintora da carga do extintor classe B é o pó químico a base de
bicarbonato de sódio;</li>
            <li>Classe C: Combate o fogo em equipamentos elétricos e energizados, como cabos,
geradores e eletrodomésticos. . A substância extintora da carga do extintor classe C é
o gás carbônico (CO2);</li>
            <li>Classe D: Combate o fogo em metais que podem entrar em combustão, como o
magnésio e o titânio. . A substância extintora da carga do extintor classe D é o pó
químico a base de cloreto de sódio;</li>
            <li>Classe K: Combate o fodo em óleos animal e vegetal, como óleo de cozinha e banha,
por isso, é o chamado extintor de cozinha. A substância extintora da carga do extintor
classe K é o acetato de potássio.</li>
</ul>


