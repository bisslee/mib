                  <p>SAIBA TUDO SOBRE O EXTINTOR DE INCÊNDIO PÓ QUÍMICO ABC.</p>

                  <p>Opções: Portátil ou sobre rodas.</p>


                  <p>Um incêndio pode ser categorizado em diferentes classes para as quais podem ser
indicados diferentes extintores, sendo que um deles é conhecido como extintor de
incêndio pó químico ABC.</p>

<p>O extintor de incêndio pó químico ABC utiliza monofosfato de amônia siliconizado
como agente extintor. Mas, antes de qualquer coisa, é importante entender quando
esse equipamento deve ser utilizado.</p>

<p>QUANDO UTILIZAR EXTINTOR DE INCÊNDIO PÓ QUÍMICO ABC?</p>

<p>Leves e com alta eficiência, os extintores do tipo ABC são fáceis de operar e têm uso
universal. Esses equipamentos são indicados para proteção residencial e comercial,
com aplicação para as indústrias.</p>

<p>Antes de escolher o extintor de incêndio pó químico ABC para extinguir o fogo é
importante identificar o tipo de incêndio a ser combatido.</p>
<ul>
            <li>INCÊNDIO TIPO A</li>
</ul>

<p>Os incêndios do tipo classe A ocorrem em materiais sólidos, fibrosos e de fácil
combustão e deixam resíduos como cinzas ou brasas.</p>

<ul>
            <li>INCÊNDIO TIPO B</li>
</ul>

<p>Os incêndios da classe B são causados por materiais inflamáveis, que queimam apenas
na superfície e, geralmente, não deixam resíduos.</p>

<ul>
            <li>INCÊNDIO TIPO C</li>
</ul>

<p>A classe C engloba os incêndios causados por equipamentos elétricos energizados e
representa um risco muito alto.</p>

<ul>
            <li>INCÊNDIO TIPO D</li>
</ul>

<p>Os incêndios tipo D, mais letais e destruidores, são causados por metais pirofóricos
que têm capacidade de entrar em combustão com substâncias comuns, como o
oxigênio.</p>

<ul>
            <li>INCÊNDIO TIPO K</li>
</ul>

<p>Por fim, os incêndios da classe K são causados por óleos e gorduras animais e vegetais,
que são utilizados para cozinhar alimentos.</p>

<p>PRINCIPAIS CARACTERÍSTICAS DO EXTINTOR DE INCÊNCIO PÓ QUÍMICO ABC</p>

<p>A principal característica desse tipo de equipamento é o fato de abafar o fogo
interrompendo a cadeia de combustão sem que ocorra condução de eletricidade. Além
disso, a cortina criada pela vazão do pó protege o operador do fogo e do calor.
O pó presente nesse tipo de extintor isola quimicamente os materiais combustíveis de
classe A (pois derrete e adere à superfície do material em combustão), abafa e
interrompe a reação em cadeia de incêndios classe B e não conduz eletricidade.</p>

