<p>Afinal, durante a vistoria do Corpo de Bombeiros sempre é feita a verificação dos
equipamentos, seu estado de conservação e adequação às normas e regulamentos da
ABNT no que tange a qualidade e confiabilidade dos dispositivos de combate ao fogo.
Por isso, o mais indicado é adquiri-los junto a um fornecedor de confiança, como a BS
