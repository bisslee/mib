// ===== INICIALIZAÇÃO =====
function initializeCarousel() {
    // Inicializa o primeiro slide de cada carrossel
    const desktopSlides = document.querySelectorAll('.desktop-carousel .hero-slide');
    const tabletSlides = document.querySelectorAll('.tablet-carousel .hero-slide');
    const mobileSlides = document.querySelectorAll('.mobile-carousel .hero-slide');
    
    
    // Remove active de todos os slides primeiro
    document.querySelectorAll('.hero-slide').forEach(slide => slide.classList.remove('active'));
    document.querySelectorAll('.indicator').forEach(indicator => indicator.classList.remove('active'));
    
    // Ativa o primeiro slide baseado no tamanho da tela
    if (window.innerWidth > 1024) {
        if (desktopSlides.length > 0) {
            desktopSlides[0].classList.add('active');
            const desktopIndicators = document.querySelectorAll('.desktop-carousel .indicator');
            if (desktopIndicators.length > 0) {
                desktopIndicators[0].classList.add('active');
            }
        }
    } else if (window.innerWidth > 768) {
        if (tabletSlides.length > 0) {
            tabletSlides[0].classList.add('active');
            const tabletIndicators = document.querySelectorAll('.tablet-carousel .indicator');
            if (tabletIndicators.length > 0) {
                tabletIndicators[0].classList.add('active');
            }
        }
    } else {
        if (mobileSlides.length > 0) {
            mobileSlides[0].classList.add('active');
            const mobileIndicators = document.querySelectorAll('.mobile-carousel .indicator');
            if (mobileIndicators.length > 0) {
                mobileIndicators[0].classList.add('active');
            }
        }
    }
}


// ===== AUTO-PLAY =====
// Auto-play para carrossel principal
let autoPlayInterval;

function calculateTotalSlides() {
    // Calcula dinamicamente o total de slides para cada carrossel
    const desktopSlides = document.querySelectorAll('.desktop-carousel .hero-slide');
    const tabletSlides = document.querySelectorAll('.tablet-carousel .hero-slide');
    const mobileSlides = document.querySelectorAll('.mobile-carousel .hero-slide');
    
    totalDesktopSlides = desktopSlides.length;
    totalTabletSlides = tabletSlides.length;
    totalMobileSlides = mobileSlides.length;
}

function resetSlideCounters() {
    // Reseta todos os contadores para 0
    currentDesktopSlide = 0;
    currentTabletSlide = 0;
    currentMobileSlide = 0;
}

function startAutoPlay() {
    // Limpa o intervalo anterior se existir
    if (autoPlayInterval) {
        clearInterval(autoPlayInterval);
    }
    
    // Calcula o total de slides dinamicamente
    calculateTotalSlides();
    
    // Reseta os contadores
    resetSlideCounters();
    
    // Inicia novo auto-play baseado no tamanho da tela
    autoPlayInterval = setInterval(() => {
        if (window.innerWidth > 1024) {
            changeDesktopSlide(1);
        } else if (window.innerWidth > 768) {
            changeTabletSlide(1);
        } else {
            changeMobileSlide(1);
        }
    }, 8000);
}

// Inicia o auto-play após a inicialização
document.addEventListener('DOMContentLoaded', function() {
    setTimeout(() => {
        initializeCarousel();
        startAutoPlay();
    }, 100);
});

