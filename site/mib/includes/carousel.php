// ===== CARROSSEL DESKTOP =====
let currentDesktopSlide = 0; // Começa no índice 0
let totalDesktopSlides = 0; // Será calculado dinamicamente

function changeDesktopSlide(direction) {
    const slides = document.querySelectorAll('.desktop-carousel .hero-slide');
    const indicators = document.querySelectorAll('.desktop-carousel .indicator');
    
    // Remove active class de TODOS os slides primeiro
    document.querySelectorAll('.hero-slide').forEach(slide => slide.classList.remove('active'));
    document.querySelectorAll('.indicator').forEach(indicator => indicator.classList.remove('active'));
    
    // Calcula próximo slide (usando índices 0 a total-1)
    currentDesktopSlide += direction;
    
    // Corrige o loop: se >= total, volta para 0
    if (currentDesktopSlide >= totalDesktopSlides) {
        currentDesktopSlide = 0;
    }
    // Se < 0, vai para o último slide (total-1)
    if (currentDesktopSlide < 0) {
        currentDesktopSlide = totalDesktopSlides - 1;
    }
    
    // Adiciona active class ao novo slide
    if (slides[currentDesktopSlide]) {
        slides[currentDesktopSlide].classList.add('active');
    }
    if (indicators[currentDesktopSlide]) {
        indicators[currentDesktopSlide].classList.add('active');
    }
}

function goToDesktopSlide(slideNumber) {
    const slides = document.querySelectorAll('.desktop-carousel .hero-slide');
    const indicators = document.querySelectorAll('.desktop-carousel .indicator');
    
    // Remove active class de TODOS os slides primeiro
    document.querySelectorAll('.hero-slide').forEach(slide => slide.classList.remove('active'));
    document.querySelectorAll('.indicator').forEach(indicator => indicator.classList.remove('active'));
    
    // Adiciona active class ao slide selecionado (slideNumber já vem como índice 0-based)
    currentDesktopSlide = slideNumber;
    if (slides[slideNumber]) {
        slides[slideNumber].classList.add('active');
    }
    if (indicators[slideNumber]) {
        indicators[slideNumber].classList.add('active');
    }
}

